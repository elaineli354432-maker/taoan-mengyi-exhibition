export const getScenePassages = (sceneId: string) =>
  scenePassages.filter((passage) => passage.sceneId === sceneId).sort((a, b) => a.order - b.order)

export const getScenePassageIds = (eventId: string) =>
  scenePassages
    .filter((passage) => passage.eventId === eventId)
    .sort((a, b) => a.order - b.order)
    .map((passage) => passage.id)

export const getChapterScenePassageIds = (chapterId: string) =>
  scenePassages
    .filter((passage) => passage.chapterId === chapterId)
    .sort((a, b) => a.order - b.order)
    .map((passage) => passage.id)

export const getScenePassage = (id: string) => scenePassages.find((passage) => passage.id === id)
